package com.omar.postify.entities;

import com.omar.postify.entities.enums.InteractionEventType;
import com.omar.postify.entities.enums.InteractionSource;
import jakarta.persistence.*;
import lombok.*;

import java.time.Instant;

@Entity
@Table(
        name = "interaction_events",
        indexes = {
                @Index(
                        name = "idx_interaction_user",
                        columnList = "user_id"
                ),
                @Index(
                        name = "idx_interaction_post",
                        columnList = "post_id"
                ),
                @Index(
                        name = "idx_interaction_user_time",
                        columnList = "user_id, occurred_at"
                ),
                @Index(
                        name = "idx_interaction_post_time",
                        columnList = "post_id, occurred_at"
                ),
                @Index(
                        name = "idx_interaction_type_time",
                        columnList = "event_type, occurred_at"
                ),
                @Index(
                        name = "idx_interaction_session",
                        columnList = "session_id"
                )
        }
)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class InteractionEvent {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
            name = "user_id",
            nullable = false,
            foreignKey = @ForeignKey(name = "fk_interaction_user")
    )
    private User user;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
            name = "anonymous_user_id",
            foreignKey = @ForeignKey(name = "fk_interaction_anonymous_user")
    )
    private AnonymousUser anonymousUser;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
            name = "post_id",
            nullable = false,
            foreignKey = @ForeignKey(name = "fk_interaction_post")
    )
    private Post post;

    @Enumerated(EnumType.STRING)
    @Column(
            name = "event_type",
            nullable = false,
            length = 32
    )
    private InteractionEventType eventType;

    /**
     * When the interaction actually happened on the client.
     */
    @Column(
            name = "occurred_at",
            nullable = false
    )
    private Instant occurredAt;

    /**
     * When the backend received the event.
     */
    @Column(
            name = "received_at",
            nullable = false
    )
    private Instant receivedAt;

    /**
     * Groups interactions belonging to the same browsing session.
     */
    @Column(
            name = "session_id",
            length = 100
    )
    private String sessionId;

    /**
     * ID generated by the client.
     *
     * Useful for idempotency when the frontend retries
     * an event because of a network failure.
     */
    @Column(
            name = "client_event_id",
            length = 100,
            unique = true
    )
    private String clientEventId;

    /**
     * Position in a video when the event occurred.
     */
    @Column(name = "position_ms")
    private Long positionMs;

    /**
     * How long the user consumed the content.
     */
    @Column(name = "duration_ms")
    private Long durationMs;

    /**
     * 0.0 -> 1.0
     */
    @Column(name = "completion_ratio")
    private Double completionRatio;

    @Enumerated(EnumType.STRING)
    @Column(
            name = "source",
            length = 32
    )
    private InteractionSource source;

    /**
     * Flexible event-specific information.
     *
     * Example:
     * {
     *   "viewportPercent": 85,
     *   "mediaIndex": 2,
     *   "referrerPostId": 123
     * }
     */
    @Column(
            name = "metadata",
            columnDefinition = "JSON"
    )
    private String metadata;

    /**
     * Allows the meaning/schema of events to evolve
     * without breaking historical data.
     */
    @Column(
            name = "event_version",
            nullable = false
    )
    @Builder.Default
    private Integer eventVersion = 1;

    @PrePersist
    protected void onCreate() {

        if (occurredAt == null) {
            occurredAt = Instant.now();
        }

        if (receivedAt == null) {
            receivedAt = Instant.now();
        }

        if (eventVersion == null) {
            eventVersion = 1;
        }

        validateOwner();
    }

    @PreUpdate
    protected void onUpdate() {
        validateOwner();
    }

    private void validateOwner() {

        boolean hasUser = user != null;
        boolean hasAnonymousUser = anonymousUser != null;

        if (hasUser == hasAnonymousUser) {
            throw new IllegalStateException(
                    "InteractionEvent must belong to exactly one identity"
            );
        }
    }
}